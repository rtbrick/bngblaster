"""
BNG Blaster LDP label withdraw and session down

One BNG Blaster instance with two LDP instances connected by a veth pair.
LDP instance 1 advertises labels generated by ldpupdate, which are used by
the streams of LDP instance 2 (ldp-ipv4-lookup-address). Labels withdrawn
by the peer and labels of sessions which went down must not be used.

Copyright (C) 2020-2026, RtBrick, Inc.
SPDX-License-Identifier: BSD-3-Clause
"""
import time

import pytest

from helpers import BngBlaster, ldpupdate, wait_until

LSR_ID_1, LSR_ID_2 = "10.2.3.1", "10.2.3.2"
PREFIXES = 10
WITHDRAWN = 5
LABEL_BASE = 10000


def prefix(i):
    return "13.37.0.%d" % i


@pytest.fixture
def bbl(local_veth, processes, tmp_path):
    def start(config):
        instance = BngBlaster(local_veth.ns, tmp_path).start(config, logging=("info", "ldp"))
        processes.append(instance)
        return instance
    return start


def test_ldp_withdraw(local_veth, bbl, tmp_path):
    update, withdraw = str(tmp_path / "update.ldp"), str(tmp_path / "withdraw.ldp")
    common = ["-l", LSR_ID_1, "-p", prefix(0) + "/32", "-m", str(LABEL_BASE), "-M", str(PREFIXES)]
    ldpupdate(common + ["-P", str(PREFIXES), "-f", update])
    # Label withdraw messages with label TLV for the first prefixes.
    ldpupdate(common + ["-P", str(WITHDRAWN), "-w", "-f", withdraw])
    instance = bbl({
        "interfaces": {
            "network": [
                {"interface": local_veth.if1, "address": "10.0.0.1/24", "gateway": "10.0.0.2",
                 "ldp-instance-id": 1},
                {"interface": local_veth.if2, "address": "10.0.0.2/24", "gateway": "10.0.0.1",
                 "ldp-instance-id": 2}
            ]
        },
        "ldp": [
            {"instance-id": 1, "lsr-id": LSR_ID_1, "raw-update-file": update},
            {"instance-id": 2, "lsr-id": LSR_ID_2}
        ],
        "ldp-raw-update-files": [withdraw],
        "streams": [{
            "name": "S%d" % i,
            "type": "ipv4",
            "direction": "downstream",
            "pps": 100,
            "network-interface": local_veth.if2,
            "destination-ipv4-address": "100.0.0.1",
            "ldp-ipv4-lookup-address": prefix(i),
            "rx-label1": LABEL_BASE + i
        } for i in range(PREFIXES)]
    })

    def active():
        """Prefixes with active labels learned by LDP instance 2."""
        db = instance.ctrl("ldp-database", **{"ldp-instance-id": 2})["ldp-database"]
        return {e["prefix"].split("/")[0] for e in db if e["active"] and e["prefix"].startswith("13.37.")}

    def tx_packets():
        return [instance.ctrl("stream-info", **{"flow-id": i + 1})["stream-info"]["tx-packets"]
                for i in range(PREFIXES)]

    def sending():
        """Streams sending within one second."""
        before = tx_packets()
        time.sleep(1)
        return {i for i, (a, b) in enumerate(zip(before, tx_packets())) if b > a}

    all_prefixes = {prefix(i) for i in range(PREFIXES)}
    remaining = {prefix(i) for i in range(WITHDRAWN, PREFIXES)}
    wait_until(lambda: active() == all_prefixes, 30, message="labels learned")
    wait_until(lambda: sending() == set(range(PREFIXES)), 10, message="all streams sending")
    wait_until(lambda: all(instance.ctrl("stream-info", **{"flow-id": i + 1})["stream-info"]["rx-packets"]
                           for i in range(PREFIXES)), 10, message="all streams received")

    # Withdrawn labels are not used anymore.
    instance.ctrl("ldp-raw-update", file=withdraw, **{"ldp-instance-id": 1})
    wait_until(lambda: active() == remaining, 10, message="labels withdrawn")
    wait_until(lambda: sending() == set(range(WITHDRAWN, PREFIXES)), 10,
               message="streams of withdrawn labels stopped")

    # Advertised again, the streams continue.
    instance.ctrl("ldp-raw-update", file=update, **{"ldp-instance-id": 1})
    wait_until(lambda: active() == all_prefixes, 10, message="labels advertised again")
    wait_until(lambda: sending() == set(range(PREFIXES)), 10, message="all streams sending again")

    # Labels of a session which went down are not used anymore.
    instance.ctrl("ldp-disconnect", **{"ldp-instance-id": 2})
    wait_until(lambda: not active(), 4, 0.2, message="labels removed with session down")
