import json
import re

import helpers
from helpers import BngBlaster, Frr, lspgen, wait_until

BBL_ADDRESS = "10.0.0.1"
BBL_ADDRESS6 = "fd00::1"
BBL_ROUTER_ID = "10.10.0.1"
FRR_ADDRESS = "10.0.0.2"
FRR_ADDRESS6 = "fd00::2"
FRR_ROUTER_ID = "10.10.0.2"

ISIS_AREA = "49.0001"
BBL_SYSTEM_ID = "1921.6800.1001"
FRR_SYSTEM_ID = "1921.6800.1002"
LSPGEN_ROOT_SYSTEM_ID = "1921.6800.0000"
LSPGEN_ROOT_ROUTER_ID = "192.168.0.0"
LSPGEN_ROOT_LINK = "10.10.1.1"
BBL_LINK = "10.10.1.0"

# FRR levels and circuit types by BNG Blaster ISIS level.
FRR_IS_TYPE = {1: "level-1", 2: "level-2-only", 3: "level-1-2"}
FRR_CIRCUIT_TYPE = {1: "level-1", 2: "level-2-only", 3: "level-1-2"}
FRR_ISIS_AUTH = {"md5": "md5", "simple": "clear"}

# Dummy interface prefixes redistributed by FRR.
FRR_PREFIX = "10.99.%d.0/24"
FRR_ADDRESS_DUMMY = "10.99.%d.1/24"
FRR_ADDRESS6_DUMMY = "fd99:%x::1/64"


class LspgenTopology:
    """Topology generated by lspgen, written as MRT file for the BNG
    Blaster and as JSON config to derive the expected nodes and routes."""

    def __init__(self, path, args):
        self.mrt = str(path.with_suffix(".mrt"))
        config = path.with_suffix(".json")
        lspgen(args + ["-m", self.mrt, "-w", str(config)], cwd=str(path.parent))
        self.nodes, self.prefixes, self.prefixes6 = set(), set(), set()
        self.prefix_sids = {}  # {prefix: {(index, algo), ...}}
        self.asla = {}  # {(node-id, remote-node-id): (te-metric, min-delay, max-delay)}
        for nodes in json.loads(config.read_text()).values():
            if not isinstance(nodes, list):
                continue
            for node in nodes:
                self.nodes.add(node["node_id"])
                for link in node.get("neighbor_list", []):
                    if "te_metric" in link:
                        self.asla[(node["node_id"], link["remote_node_id"])] = (
                            link["te_metric"], link["min_delay"], link["max_delay"])
                for p in node.get("ipv4_prefix_list", []) + node.get("ipv6_prefix_list", []):
                    sids = {(s["index"], s["algo"]) for s in p.get("segment_ids", [])}
                    if "segment_id" in p:
                        sids.add((p["segment_id"], 0))
                    if sids:
                        self.prefix_sids[p.get("ipv4_prefix") or p["ipv6_prefix"]] = sids
                self.prefixes.update(p["ipv4_prefix"] for p in node.get("ipv4_prefix_list", [])
                                     if p["ipv4_prefix"].endswith("/32"))
                self.prefixes6.update(p["ipv6_prefix"] for p in node.get("ipv6_prefix_list", [])
                                      if p["ipv6_prefix"].endswith("/128"))


def levels(level):
    return [l for l in (1, 2) if level & l]


class IgpSetup:
    """Start FRR in namespace B and the BNG Blaster in namespace A."""

    daemon = None
    logging = ("info",)

    def __init__(self, topology, processes, tmp_path):
        self.topology = topology
        self.processes = processes
        self.tmp_path = tmp_path
        self.frr = None
        self.bbl = None
        helpers.kernel_address(topology.b, topology.if_b,
                               FRR_ADDRESS + "/24", FRR_ADDRESS6 + "/64")

    def start(self, frr=None, bbl=None):
        return self.start_frr(frr).start_bbl(bbl)

    def start_frr(self, frr=None):
        self.frr = Frr(self.topology.b, self.tmp_path, (self.daemon,)).start(
            self.frr_config(**(frr or {})))
        self.processes.append(self.frr)
        return self

    def start_bbl(self, bbl=None):
        self.bbl = BngBlaster(self.topology.a, self.tmp_path).start(
            self.bbl_config(**(bbl or {})), logging=self.logging)
        self.processes.append(self.bbl)
        return self

    def frr_redistribute_connected(self, count):
        """Add prefixes 0 to count-1 on a dummy interface in namespace B
        which FRR redistributes as connected routes."""
        ns = self.topology.b
        ns.exec(["ip", "link", "add", "dummy0", "type", "dummy"])
        ns.exec(["sysctl", "-qw", "net.ipv6.conf.dummy0.disable_ipv6=0"])
        ns.exec(["ip", "link", "set", "dummy0", "up"])
        for i in range(count):
            self.frr_add_prefix(i)

    def frr_add_prefix(self, i):
        self.topology.b.exec(["ip", "addr", "add", FRR_ADDRESS_DUMMY % i, "dev", "dummy0"])
        self.topology.b.exec(["ip", "-6", "addr", "add", FRR_ADDRESS6_DUMMY % i,
                              "dev", "dummy0", "nodad"])

    def frr_del_prefix(self, i):
        self.topology.b.exec(["ip", "addr", "del", FRR_ADDRESS_DUMMY % i, "dev", "dummy0"])
        self.topology.b.exec(["ip", "-6", "addr", "del", FRR_ADDRESS6_DUMMY % i, "dev", "dummy0"])

    def frr_routes(self, afi="ip"):
        """Return prefixes installed by the IGP in the FRR routing table."""
        routes = self.frr.vtysh("show %s route %s" % (afi, self.daemon.rstrip("d")))
        return {prefix for prefix, entries in routes.items()
                if any(e.get("selected") and e.get("installed") for e in entries)}

    def frr_nexthops(self, prefix):
        afi = "ipv6" if ":" in prefix else "ip"
        routes = self.frr.vtysh("show %s route %s" % (afi, prefix))
        return [n.get("ip") for e in routes.get(prefix, []) if e.get("selected")
                for n in e.get("nexthops", [])]

    def frr_metric(self, prefix):
        """Return the metric of the selected FRR route."""
        afi = "ipv6" if ":" in prefix else "ip"
        routes = self.frr.vtysh("show %s route %s" % (afi, prefix))
        return next(e["metric"] for e in routes[prefix] if e.get("selected"))

    def teardown(self):
        assert self.bbl.terminate(30) == 0


class IsisSetup(IgpSetup):

    daemon = "isisd"
    logging = ("info", "isis")

    @staticmethod
    def lspgen(path, nodes, level=1, auth=None, sr_algo=None, flex_algo=None,
               link_delay=None, te_metric=None, node_msd=None, elc=False):
        args = ["-a", "%s/24" % ISIS_AREA, "-c", str(nodes), "-V", str(level),
                "-C", BBL_SYSTEM_ID]
        if auth:
            args += ["-K", auth[1], "-T", auth[0]]
        if sr_algo:
            args += ["-A", ",".join(str(a) for a in sr_algo)]
        if flex_algo:
            args += ["-F", flex_algo]
        if link_delay:
            args += ["-D", link_delay]
        if te_metric:
            args += ["-E", te_metric]
        if node_msd:
            args += ["-B", str(node_msd)]
        if elc:
            args.append("-O")
        return LspgenTopology(path, args)

    def frr_config(self, level=1, p2p=True, auth=None, redistribute=False, flex_algo=None,
                   link_params=None):
        """Return FRR config. The auth tuple (type, key) is used for hellos,
        LSPs and SNPs of all levels. FRR participates in the flex_algo list
        of algorithms without advertising a definition. All links must have
        subTLVs, otherwise FRR crashes (FRRouting/frr#23693)."""
        lines = [
            "router isis bbl",
            " net %s.%s.00" % (ISIS_AREA, FRR_SYSTEM_ID),
            " is-type %s" % FRR_IS_TYPE[level],
            " metric-style wide",
            " no hostname dynamic",
            " lsp-gen-interval 1",
            " spf-interval 1",
        ]
        if auth:
            auth = (FRR_ISIS_AUTH[auth[0]], auth[1])
            if level & 1:
                lines.append(" area-password %s %s authenticate snp validate" % auth)
            if level & 2:
                lines.append(" domain-password %s %s authenticate snp validate" % auth)
        if redistribute:
            for l in levels(level):
                lines.append(" redistribute ipv4 connected level-%d" % l)
                lines.append(" redistribute ipv6 connected level-%d" % l)
        if link_params:
            lines += [" mpls-te on", " mpls-te router-address %s" % FRR_ADDRESS]
        if flex_algo:
            lines += [" segment-routing on",
                      " segment-routing global-block 16000 23999"]
            for algo in flex_algo:
                lines += [" flex-algo %d" % algo, "  dataplane sr-mpls", " exit"]
        lines += [
            "exit",
            "interface %s" % self.topology.if_b,
            " ip router isis bbl",
            " ipv6 router isis bbl",
            " isis circuit-type %s" % FRR_CIRCUIT_TYPE[level],
            " isis hello-interval 1",
            " isis hello-multiplier 10",
        ]
        if p2p:
            lines.append(" isis network point-to-point")
        if auth:
            lines.append(" isis password %s %s" % auth)
        if link_params:
            # (te-metric, delay) advertised as application-specific link attributes
            lines += [" link-params", "  enable", "  metric %d" % link_params[0],
                      "  delay %d min %d max %d" % (link_params[1], link_params[1], link_params[1]), " exit-link-params"]
        lines.append("exit")
        return "\n".join(lines) + "\n"

    def bbl_config(self, level=1, p2p=True, isis=None, mrt=None, connection=None, network=None):
        instance = {
            "instance-id": 1,
            "level": level,
            "area": ["%s/24" % ISIS_AREA],
            "system-id": BBL_SYSTEM_ID,
            "router-id": BBL_ROUTER_ID,
            "hostname": "BBL",
            "hello-interval": 1,
            "hold-time": 10,
        }
        if mrt:
            external = {"system-id": "%s.00" % LSPGEN_ROOT_SYSTEM_ID}
            for l in levels(level):
                external["l%d-metric" % l] = 10
            external.update(connection or {})
            instance["external"] = {"mrt-file": mrt, "connections": [external]}
        instance.update(isis or {})
        return {
            "interfaces": {
                "network": {
                    "interface": self.topology.if_a,
                    "address": BBL_ADDRESS + "/24",
                    "gateway": FRR_ADDRESS,
                    "address-ipv6": BBL_ADDRESS6 + "/64",
                    "gateway-ipv6": FRR_ADDRESS6,
                    "isis-instance-id": 1,
                    "isis-level": level,
                    "isis-p2p": p2p,
                    **(network or {})
                }
            },
            "isis": [instance]
        }

    def bbl_adjacencies(self):
        return self.bbl.ctrl("isis-adjacencies")["isis-adjacencies"]

    def bbl_adjacency_up(self):
        adjacencies = self.bbl_adjacencies()
        return bool(adjacencies) and all(a["adjacency-state"] == "Up" for a in adjacencies)

    def frr_neighbors(self):
        """Return FRR adjacencies as list of (level, state). The text output
        is parsed, because the JSON output of FRR 10 contains only one level
        of broadcast L1L2 adjacencies."""
        result = []
        for line in self.frr.vtysh("show isis neighbor", json_output=False).splitlines():
            fields = line.split()
            if len(fields) >= 4 and fields[0] == BBL_SYSTEM_ID:
                result.append((int(fields[2]), fields[3]))
        return result

    def frr_adjacency_up(self, level):
        """FRR has an adjacency in state Up for every expected level
        (P2P L1L2 adjacencies are shown as level 3)."""
        up = set()
        for l, state in self.frr_neighbors():
            if state == "Up":
                up.update(levels(l))
        return up == set(levels(level))

    def established(self, level):
        return self.bbl_adjacency_up() and self.frr_adjacency_up(level)

    def wait_established(self, level, timeout=30):
        try:
            wait_until(lambda: self.established(level), timeout, message="ISIS adjacency up")
        except TimeoutError as e:
            raise TimeoutError("%s, BNG Blaster: %s, FRR: %s" % (
                e, self.bbl_adjacencies(), self.frr_neighbors())) from None

    def assert_not_established(self, level, duration=10):
        try:
            wait_until(lambda: self.bbl_adjacency_up() or
                       any(state == "Up" for _, state in self.frr_neighbors()),
                       duration, message="ISIS adjacency")
        except TimeoutError:
            return
        raise AssertionError("ISIS adjacency up unexpectedly")

    def frr_database(self, level):
        """Return {lsp-id: sequence number} of an FRR database level."""
        result = {}
        for area in self.frr.vtysh("show isis database").get("areas", []):
            for db_level in area.get("levels", []):
                if db_level.get("id") != level:
                    continue
                for lsp in db_level.get("lsps", []):
                    result[lsp["lsp"]["id"]] = int(lsp["seqNumber"], 16)
        return result

    def frr_prefix_sids(self):
        """Return {prefix: {(index, algo), ...}} and {lsp-id: [algo, ...]}
        of all LSPs parsed from the FRR detail text output."""
        sids, algos = {}, {}
        lsp = prefix = None
        in_algo = False
        for line in self.frr.vtysh("show isis database detail", json_output=False).splitlines():
            fields = line.split()
            if re.match(r"^[0-9a-f.]+-\d\d\s", line):
                lsp, in_algo = fields[0], False
            elif "Reachability:" in line and "/" in line:
                prefix = fields[-3]
            elif "SR Algorithm:" in line:
                in_algo = True
                algos[lsp] = []
            elif in_algo and re.match(r"^\s+\d+:", line):
                algos[lsp].append(int(fields[0].rstrip(":")))
            elif "SR Prefix-SID Index:" in line:
                m = re.search(r"Index: (\d+), Algorithm: (\d+)", line)
                sids.setdefault(prefix, set()).add((int(m.group(1)), int(m.group(2))))
            else:
                in_algo = in_algo and line.startswith("      ")
        return sids, algos

    def frr_flex_algo_definitions(self):
        """Return {lsp-id: {algo: {field: value}}} of all Flex-Algo
        definitions parsed from the FRR detail text output."""
        result = {}
        lsp = fad = None
        for line in self.frr.vtysh("show isis database detail", json_output=False).splitlines():
            if re.match(r"^[0-9a-f.]+-\d\d\s", line):
                lsp, fad = line.split()[0], None
            elif "Flex-Algo Definition:" in line:
                fad = result.setdefault(lsp, {}).setdefault(int(line.split()[-1]), {})
            elif fad is not None and re.match(r"^\s{6}[A-Za-z-]+: ", line):
                key, value = line.strip().split(": ", 1)
                fad[key] = value.strip()
            else:
                fad = None
        return result

    def frr_asla(self):
        """Return {(lsp-id, neighbor): (te-metric, min-delay, max-delay)} of all
        Flex-Algo application-specific link attributes parsed from the FRR detail
        text output."""
        result = {}
        lsp = reach = None
        for line in self.frr.vtysh("show isis database detail", json_output=False).splitlines():
            if re.match(r"^[0-9a-f.]+-\d\d\s", line):
                lsp, reach = line.split()[0], None
            elif "Extended Reachability:" in line:
                reach = [line.split()[2], None, None]
            elif reach and "Traffic Engineering Metric:" in line:
                reach[1] = int(line.split()[-1])
            elif reach and "Min/Max Link Delay:" in line:
                m = re.search(r"(\d+) / (\d+)", line)
                result[(lsp, reach[0])] = (reach[1], int(m.group(1)), int(m.group(2)))
        return result

    def frr_flex_algo_source(self, algo):
        """Return the source system-id of the elected Flex-Algo definition."""
        text = self.frr.vtysh("show isis flex-algo %d" % algo, json_output=False)
        m = re.search(r"Source: (\S+)", text)
        return m.group(1) if m else None

    def frr_algo_routes(self, algo):
        """Return the IP prefixes of the FRR SPF result of an algorithm."""
        text = self.frr.vtysh("show isis route algorithm %d" % algo, json_output=False)
        return {line.split()[0] for line in text.splitlines()
                if re.match(r"^ \S+/\d+\s+IP", line)}

    def frr_node_msd(self, level):
        """Return {lsp-id: node MSD} of an FRR database level."""
        result = {}
        for area in self.frr.vtysh("show isis database detail").get("areas", []):
            for db_level in area.get("levels", []):
                if db_level.get("id") == level:
                    for lsp in db_level.get("lsps", []):
                        if "msd" in lsp:
                            result[lsp["lsp"]["id"]] = lsp["msd"]
        return result

    def frr_lsp(self, level, lsp_id):
        """Return an LSP of an FRR database level (detail output)."""
        for area in self.frr.vtysh("show isis database detail").get("areas", []):
            for db_level in area.get("levels", []):
                if db_level.get("id") != level:
                    continue
                for lsp in db_level.get("lsps", []):
                    if lsp["lsp"]["id"] == lsp_id:
                        return lsp
        return None

    def frr_overload(self, level, lsp_id):
        """FRR shows the ATT/P/OL bits of an LSP as e.g. 0/0/1."""
        lsp = self.frr_lsp(level, lsp_id)
        return bool(lsp) and lsp.get("attPOl", "").strip().endswith("/1")

    def bbl_database(self, level):
        """Return {lsp-id: sequence number} of a BNG Blaster database level."""
        entries = self.bbl.ctrl("isis-database", instance=1, level=level)["isis-database"]
        return {e["id"]: e["seq"] for e in entries}


class OspfSetup(IgpSetup):

    daemon = "ospfd"
    logging = ("info", "ospf")

    @staticmethod
    def lspgen(path, nodes):
        # The protocol must be set before the connector.
        return LspgenTopology(path, ["-P", "ospf2", "-c", str(nodes),
                                     "-C", "%s:%s" % (BBL_ROUTER_ID, LSPGEN_ROOT_LINK)])

    def frr_config(self, p2p=True, auth=None, redistribute=False, priority=None, opaque=True):
        """Return FRR config. The auth tuple is (type, key) with
        type simple or md5 (key ID 1)."""
        lines = [
            "router ospf",
            " ospf router-id %s" % FRR_ROUTER_ID,
            " timers throttle spf 0 50 200",
            " timers throttle lsa all 0",
        ]
        if opaque:
            # Required for the SR opaque LSAs generated by lspgen.
            lines.append(" capability opaque")
        if redistribute:
            lines.append(" redistribute connected")
        lines += [
            "exit",
            "interface %s" % self.topology.if_b,
            " ip ospf network %s" % ("point-to-point" if p2p else "broadcast"),
            " ip ospf hello-interval 1",
            " ip ospf dead-interval 4",
        ]
        if priority is not None:
            lines.append(" ip ospf priority %d" % priority)
        if auth and auth[0] == "md5":
            lines += [" ip ospf authentication message-digest",
                      " ip ospf message-digest-key 1 md5 %s" % auth[1]]
        elif auth:
            lines += [" ip ospf authentication",
                      " ip ospf authentication-key %s" % auth[1]]
        # The area enables OSPF on the interface, so it must be configured
        # last, otherwise the wait timer starts with the default dead interval.
        lines += [" ip ospf area 0.0.0.0", "exit"]
        return "\n".join(lines) + "\n"

    def bbl_config(self, p2p=True, ospf=None, mrt=None, version=2):
        instance = {
            "instance-id": 1,
            "version": version,
            "router-id": BBL_ROUTER_ID,
            "hostname": "BBL",
            "hello-interval": 1,
            "dead-interval": 4,
        }
        if mrt:
            instance["external"] = {"mrt-file": mrt, "connections": [{
                "router-id": LSPGEN_ROOT_ROUTER_ID,
                "local-ipv4-address": BBL_LINK,
                "metric": 10
            }]}
        instance.update(ospf or {})
        network = {
            "interface": self.topology.if_a,
            "address": BBL_ADDRESS + "/24",
            "gateway": FRR_ADDRESS,
            "ospfv%d-instance-id" % version: 1,
            "ospfv%d-type" % version: "p2p" if p2p else "broadcast"
        }
        if version == 3:
            network["address-ipv6"] = BBL_ADDRESS6 + "/64"
            network["gateway-ipv6"] = FRR_ADDRESS6
        return {
            "interfaces": {"network": network},
            "ospf": [instance]
        }

    def bbl_neighbors(self):
        return self.bbl.ctrl("ospf-neighbors", instance=1)["ospf-neighbors"]

    def bbl_interface(self):
        return self.bbl.ctrl("ospf-interfaces", instance=1)["ospf-interfaces"][0]

    def bbl_full(self):
        neighbors = self.bbl_neighbors()
        return len(neighbors) == 1 and neighbors[0]["state"] == "Full"

    def frr_interface_state(self):
        """Return FRR interface state (e.g. DR)."""
        interfaces = self.frr.vtysh("show ip ospf interface").get("interfaces", {})
        return interfaces.get(self.topology.if_b, {}).get("state")

    def frr_neighbor_state(self):
        """Return FRR neighbor state (e.g. Full/DR) of the BNG Blaster."""
        neighbors = self.frr.vtysh("show ip ospf neighbor").get("neighbors", {})
        for entry in neighbors.get(BBL_ROUTER_ID, []):
            return entry.get("nbrState")
        return None

    def frr_full(self):
        return (self.frr_neighbor_state() or "").startswith("Full")

    def established(self):
        return self.bbl_full() and self.frr_full()

    def wait_established(self, timeout=30):
        try:
            wait_until(self.established, timeout, message="OSPF neighbor full")
        except TimeoutError as e:
            raise TimeoutError("%s, BNG Blaster: %s, FRR: %s" % (
                e, self.bbl_neighbors(), self.frr_neighbor_state())) from None

    def assert_not_established(self, duration=10):
        try:
            wait_until(lambda: self.bbl_full() or self.frr_full(), duration,
                       message="OSPF neighbor")
        except TimeoutError:
            return
        raise AssertionError("OSPF neighbor full unexpectedly")

    def bbl_database(self):
        return self.bbl.ctrl("ospf-database", instance=1)["ospf-database"]

    def frr_router_lsas(self):
        """Return advertising router IDs of all router LSAs in area 0."""
        database = self.frr.vtysh("show ip ospf database router")
        areas = database.get("routerLinkStates", {}).get("areas", {})
        return {lsa.get("advertisingRouter") for lsa in areas.get("0.0.0.0", [])}
