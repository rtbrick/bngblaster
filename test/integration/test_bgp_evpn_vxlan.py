RD = "65001:100"
RT = "65001:100"
ROUTER_MAC = "02:00:00:00:00:55"
CE_MAC = "02:00:00:00:00:cc"


@pytest.fixture
def bgp(topology, processes, tmp_path):
    return BgpSetup(topology, processes, tmp_path)


def evpn(bgp, action, route):
    bgp.gobgp.cli(["global", "rib", "-a", "evpn", action] + route, json_output=False)


def mac_address(ns, ifname):
    out = helpers.run(ns.cmd(["ip", "-j", "link", "show", ifname]))
    return json.loads(out)[0]["address"]


def scapy(ns, script, *args, timeout=30):
    return helpers.run(ns.cmd([sys.executable, "-c", script] + [str(a) for a in args]), timeout=timeout)


SNIFF_VXLAN = """
import json, sys
from scapy.all import sniff, IP, UDP, Ether
from scapy.layers.vxlan import VXLAN
iface, vni = sys.argv[1], int(sys.argv[2])
p = sniff(iface=iface, count=1, timeout=10,
          lfilter=lambda p: VXLAN in p and p[VXLAN].vni == vni)
if not p:
    sys.exit(1)
p = p[0]
inner = p[VXLAN].payload
print(json.dumps({"src": p[IP].src, "dst": p[IP].dst, "sport": p[UDP].sport, "chksum": p[UDP].chksum,
                  "inner_dst": inner[Ether].dst, "inner_src": inner[Ether].src,
                  "inner_ip_dst": inner[IP].dst}))
"""


@pytest.mark.usefixtures("gobgp_bin")
def test_evpn_vxlan_ip_prefix(bgp):
    """L3 EVPN stream to an IP prefix route with VXLAN encapsulation is sent
    to the VTEP (BGP next-hop) with the VNI and the router's MAC as inner
    destination, IP prefix routes without router's MAC are not usable."""
    if_a = bgp.topology.if_a
    streams = [{
        "name": "T5", "type": "ipv4", "direction": "downstream", "pps": 50,
        "network-interface": if_a, "destination-ipv4-address": "192.168.10.1",
        "bgp-evpn-rd": RD, "bgp-evpn-prefix": "192.168.10.0/24"
    }, {
        "name": "T5-no-router-mac", "type": "ipv4", "direction": "downstream", "pps": 50,
        "network-interface": if_a, "destination-ipv4-address": "192.168.20.1",
        "bgp-evpn-rd": RD, "bgp-evpn-prefix": "192.168.20.0/24"
    }]
    bgp.start(families=("evpn",), bbl={"streams": streams})
    bgp.wait_established()
    evpn(bgp, "add", ["prefix", "192.168.10.0/24", "gw", "0.0.0.0", "etag", "0", "label", "5000",
                      "rd", RD, "rt", RT, "encap", "vxlan", "router-mac", ROUTER_MAC])
    evpn(bgp, "add", ["prefix", "192.168.20.0/24", "gw", "0.0.0.0", "etag", "0", "label", "5001",
                      "rd", RD, "rt", RT, "encap", "vxlan"])
    wait_until(lambda: len([r for r in bgp.bbl_evpn_routes() if r["active"]]) == 2, 15,
               message="EVPN IP prefix routes learned")
    bgp.bbl.ctrl("traffic-start")

    def info(flow_id):
        return bgp.bbl.ctrl("stream-info", **{"flow-id": flow_id})["stream-info"]

    i = wait_until(lambda: info(1).get("evpn-resolved") and info(1), 10, message="T5 stream resolved")
    assert i["evpn-encapsulation"] == "vxlan"
    assert i["evpn-label"] == 5000
    assert i["evpn-vtep"] == GOBGP_ADDRESS

    packet = json.loads(scapy(bgp.topology.b, SNIFF_VXLAN, bgp.topology.if_b, 5000))
    assert packet["src"] == BBL_ADDRESS
    assert packet["dst"] == GOBGP_ADDRESS
    assert 49152 <= packet["sport"] <= 65535
    assert packet["chksum"] == 0
    assert packet["inner_dst"] == ROUTER_MAC
    assert packet["inner_src"] == mac_address(bgp.topology.a, if_a)
    assert packet["inner_ip_dst"] == "192.168.10.1"

    i = info(2)
    assert i["evpn-resolved"] is False and i["tx-packets"] == 0, i
    bgp.bbl.ctrl("traffic-stop")
    bgp.teardown()


ARP_VXLAN = """
import json, sys
from scapy.all import AsyncSniffer, sendp, Ether, IP, UDP, ARP, ICMP
from scapy.layers.vxlan import VXLAN
iface, bbl_mac, bbl_ip, peer_ip, vni, ce_mac, pe_ip, ce_ip = sys.argv[1:9]
vni = int(vni)
outer = Ether(dst=bbl_mac) / IP(src=peer_ip, dst=bbl_ip) / UDP(sport=50000, dport=4789) / VXLAN(vni=vni)
sniffer = AsyncSniffer(iface=iface, lfilter=lambda p: VXLAN in p and p[IP].dst == peer_ip)
sniffer.start()
import time
time.sleep(1)
sendp(outer / Ether(dst="ff:ff:ff:ff:ff:ff", src=ce_mac) / ARP(op=1, hwsrc=ce_mac, psrc=ce_ip, pdst=pe_ip),
      iface=iface, verbose=False)
sendp(outer / Ether(dst=bbl_mac, src=ce_mac) / IP(src=ce_ip, dst=pe_ip) / ICMP(id=7, seq=1),
      iface=iface, verbose=False)
time.sleep(2)
result = []
for p in sniffer.stop():
    inner = p[VXLAN].payload
    r = {"vni": p[VXLAN].vni, "src": p[IP].src, "inner_dst": inner[Ether].dst, "inner_src": inner[Ether].src}
    if ARP in inner:
        r.update({"arp_op": inner[ARP].op, "arp_hwsrc": inner[ARP].hwsrc, "arp_psrc": inner[ARP].psrc,
                  "arp_pdst": inner[ARP].pdst})
    elif ICMP in inner:
        r.update({"icmp_type": inner[ICMP].type, "icmp_src": inner[IP].src, "icmp_dst": inner[IP].dst})
    result.append(r)
print(json.dumps(result))
"""


@pytest.mark.usefixtures("gobgp_bin")
def test_evpn_vxlan_elan_arp(bgp):
    """ARP and ICMP echo requests of a CE received within the E-LAN service
    over VXLAN (vpws-arp) are answered over VXLAN with the VNI of the
    IMET route to the VTEP of the remote PE."""
    if_a = bgp.topology.if_a
    streams = [{
        "name": "ELAN", "type": "ipv4", "direction": "downstream", "pps": 1,
        "network-interface": if_a, "network-ipv4-address": "198.51.100.1",
        "destination-ipv4-address": "198.51.100.2", "destination-mac": CE_MAC,
        "bgp-evpn-rd": RD, "bgp-evpn-elan": True, "vpws-arp": True
    }]
    bgp.start(families=("evpn",), bbl={"streams": streams})
    bgp.wait_established()
    evpn(bgp, "add", ["multicast", GOBGP_ADDRESS, "etag", "0", "rd", RD, "rt", RT, "encap", "vxlan",
                      "pmsi", "ingress-repl", "3000", GOBGP_ADDRESS])
    wait_until(lambda: any(r["active"] for r in bgp.bbl_evpn_routes()), 15, message="EVPN IMET route learned")

    bbl_mac = mac_address(bgp.topology.a, if_a)
    out = scapy(bgp.topology.b, ARP_VXLAN, bgp.topology.if_b, bbl_mac, BBL_ADDRESS, GOBGP_ADDRESS,
                3000, CE_MAC, "198.51.100.1", "198.51.100.2")
    replies = json.loads(out)
    arp = [r for r in replies if r.get("arp_op") == 2]
    icmp = [r for r in replies if r.get("icmp_type") == 0]
    assert len(arp) == 1 and len(icmp) == 1, replies
    for r in arp + icmp:
        assert r["vni"] == 3000
        assert r["src"] == BBL_ADDRESS
        assert r["inner_dst"] == CE_MAC
        assert r["inner_src"] == bbl_mac
    assert arp[0]["arp_hwsrc"] == bbl_mac
    assert arp[0]["arp_psrc"] == "198.51.100.1"
    assert arp[0]["arp_pdst"] == "198.51.100.2"
    assert icmp[0]["icmp_src"] == "198.51.100.1"
    assert icmp[0]["icmp_dst"] == "198.51.100.2"
    bgp.teardown()


@pytest.mark.usefixtures("gobgp_bin")
def test_evpn_vxlan_to_gobgp(bgp, tmp_path):
    """EVPN E-LAN and VPWS routes with VXLAN encapsulation sent by the BNG
    Blaster carry the VNI in the label fields and the PMSI tunnel attribute."""
    path = str(tmp_path / "evpn.bgp")
    bgpupdate(["-f", path, "-l", "100", "-n", BBL_ADDRESS, "--evpn-elan", "--rd", "65000:1", "--rt", "65000:1",
               "--vni", "70000", "--mac", "02:00:00:00:00:01"])
    bgpupdate(["-f", path, "--append", "-l", "100", "-n", BBL_ADDRESS, "--evpn-vpws", "--rd", "65000:2",
               "--rt", "65000:2", "--vni", "80000", "--service-id", "10", "--end-of-rib"])
    bgp.start(families=("evpn",), bbl={"bgp": {"raw-update-file": path}})
    bgp.wait_established()
    routes = wait_until(lambda: len(bgp.gobgp.adj_in(BBL_ADDRESS, "evpn")) == 3 and
                        bgp.gobgp.adj_in(BBL_ADDRESS, "evpn"), 15,
                        message="GoBGP EVPN VXLAN routes received")
    by_type = {paths[0]["nlri"]["type"]: paths[0] for paths in routes.values()}
    assert by_type[1]["nlri"]["value"]["label"] == 80000
    assert by_type[1]["nlri"]["value"]["etag"] == 10
    assert by_type[2]["nlri"]["value"]["labels"] == [70000]
    for route_type in (2, 3):
        attrs = {a["type"]: a for a in by_type[route_type]["attrs"]}
        assert {"type": 3, "subtype": 12, "tunnel_type": 8} in attrs[16]["value"], attrs[16]
    pmsi = {a["type"]: a for a in by_type[3]["attrs"]}[22]
    assert pmsi["label"] == 70000, pmsi
    assert pmsi["tunnel-type"] == 6, pmsi  # ingress replication
    bgp.teardown()
