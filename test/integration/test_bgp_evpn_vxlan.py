"""
BNG Blaster BGP EVPN with VXLAN encapsulation (RFC 8365)

One BNG Blaster instance emulates two PEs (VTEPs) connected by a veth
pair, each with an internal BGP session to the other PE advertising
EVPN E-LAN and VPWS routes with VXLAN encapsulation generated by
bgpupdate --vni. The traffic streams resolve the VNI and VTEP from the
routes of the other PE, which verifies the VNI advertised by itself.

The IP prefix routes (L3 EVPN) and the replies to ARP and ICMP echo
requests within an E-LAN service (vpws-arp) are tested against GoBGP.

Copyright (C) 2020-2026, RtBrick, Inc.
SPDX-License-Identifier: BSD-3-Clause
"""
import json
import sys

import pytest

import helpers
from bgp_common import BBL_ADDRESS, GOBGP_ADDRESS, BgpSetup
from helpers import BngBlaster, bgpupdate, wait_until

AS = 65000
PE_A, PE_B = "10.0.0.1", "10.0.0.2"
RT_ELAN, RT_VPWS = "65000:100", "65000:200"
ELAN_RD = {PE_A: "10.0.0.1:100", PE_B: "10.0.0.2:100"}
VPWS_RD = {PE_A: "10.0.0.1:200", PE_B: "10.0.0.2:200"}
ELAN_VNI = {PE_A: 1100, PE_B: 2100}
VPWS_VNI = {PE_A: 1200, PE_B: 2200}
SERVICE_ID = {PE_A: 1, PE_B: 2}
MAC = {PE_A: "02:00:00:00:0a:01", PE_B: "02:00:00:00:0b:01"}
UNKNOWN_MAC = "02:00:00:00:0b:99"


@pytest.fixture
def bbl(local_veth, processes, tmp_path):
    def start(config):
        instance = BngBlaster(local_veth.ns, tmp_path).start(config, logging=("info", "bgp"))
        processes.append(instance)
        return instance
    return start


def evpn_update(path, pe):
    bgpupdate(["-f", path, "-l", "100", "-n", pe, "--evpn-elan", "--rd", ELAN_RD[pe], "--rt", RT_ELAN,
               "--vni", str(ELAN_VNI[pe]), "--mac", MAC[pe]])
    bgpupdate(["-f", path, "--append", "-l", "100", "-n", pe, "--evpn-vpws", "--rd", VPWS_RD[pe],
               "--rt", RT_VPWS, "--vni", str(VPWS_VNI[pe]), "--service-id", str(SERVICE_ID[pe]),
               "--end-of-rib"])


def session(local, peer, raw_update):
    return {
        "local-ipv4-address": local,
        "peer-ipv4-address": peer,
        "local-as": AS,
        "peer-as": AS,
        "learn-routes": True,
        "family": ["evpn"],
        "raw-update-file": raw_update
    }


def stream(name, interface, local, remote, **extra):
    config = {
        "name": name,
        "type": "ipv4",
        "direction": "downstream",
        "pps": 100,
        "network-interface": interface,
        "network-ipv4-address": "192.0.2.%s" % local.split(".")[-1],
        "destination-ipv4-address": "192.0.2.%s" % remote.split(".")[-1],
    }
    config.update(extra)
    return config


def elan(name, interface, local, remote, mac, rx_vni):
    return stream(name, interface, local, remote, **{
        "destination-mac": mac,
        "bgp-evpn-rd": ELAN_RD[remote],
        "bgp-evpn-elan": True,
        "rx-vni": rx_vni})


def vpws(name, interface, local, remote):
    return stream(name, interface, local, remote, **{
        "destination-mac": MAC[remote],
        "bgp-evpn-rd": VPWS_RD[remote],
        "bgp-evpn-ethernet-tag": SERVICE_ID[remote],
        "rx-vni": VPWS_VNI[remote]})


STREAMS = ["elan-A-B", "elan-B-A", "elan-A-unknown", "vpws-A-B", "vpws-B-A"]


@pytest.mark.parametrize("threads", [False, True], ids=["main", "threads"])
def test_evpn_vxlan_streams(local_veth, bbl, tmp_path, threads):
    update_a, update_b = str(tmp_path / "a.bgp"), str(tmp_path / "b.bgp")
    evpn_update(update_a, PE_A)
    evpn_update(update_b, PE_B)
    if1, if2 = local_veth.if1, local_veth.if2
    instance = bbl({
        "interfaces": {
            "network": [
                {"interface": if1, "address": PE_A + "/24", "gateway": PE_B},
                {"interface": if2, "address": PE_B + "/24", "gateway": PE_A}
            ],
            # Streams sent by TX threads, which read the routes while updated.
            "links": [{"interface": i, "tx-threads": 1, "rx-threads": 1}
                      for i in (if1, if2)] if threads else []
        },
        "bgp": [session(PE_A, PE_B, update_a), session(PE_B, PE_A, update_b)],
        "streams": [
            # Known unicast (MAC/IP route) and unknown unicast (IMET route).
            elan("elan-A-B", if1, PE_A, PE_B, MAC[PE_B], ELAN_VNI[PE_B]),
            elan("elan-B-A", if2, PE_B, PE_A, MAC[PE_A], ELAN_VNI[PE_A]),
            elan("elan-A-unknown", if1, PE_A, PE_B, UNKNOWN_MAC, ELAN_VNI[PE_B]),
            vpws("vpws-A-B", if1, PE_A, PE_B),
            vpws("vpws-B-A", if2, PE_B, PE_A),
            # Received with VNI 2100, not verified.
            elan("elan-wrong-vni", if1, PE_A, PE_B, MAC[PE_B], 9999)
        ]
    })

    def info(name):
        flow_id = STREAMS.index(name) + 1 if name in STREAMS else len(STREAMS) + 1
        result = instance.ctrl("stream-info", **{"flow-id": flow_id})["stream-info"]
        assert result["name"] == name
        return result

    def verified():
        return all(info(n)["rx-packets"] >= 100 and info(n)["rx-loss"] == 0 for n in STREAMS)

    wait_until(verified, 60, message="EVPN VXLAN streams verified")

    expected = {
        "elan-A-B": (ELAN_VNI[PE_B], 2, PE_B),
        "elan-B-A": (ELAN_VNI[PE_A], 2, PE_A),
        "elan-A-unknown": (ELAN_VNI[PE_B], 3, PE_B),
        "vpws-A-B": (VPWS_VNI[PE_B], 1, PE_B),
        "vpws-B-A": (VPWS_VNI[PE_A], 1, PE_A),
    }
    for name, (vni, route_type, vtep) in expected.items():
        i = info(name)
        assert i["evpn-resolved"] is True, i
        assert i["evpn-encapsulation"] == "vxlan", i
        assert i["evpn-label"] == vni, i
        assert i["evpn-route-type"] == route_type, i
        assert i["evpn-vtep"] == vtep, i
        assert i["rx-vni"] == vni, i
        assert i["rx-vni-expected"] == vni, i

    wrong = info("elan-wrong-vni")
    assert wrong["tx-packets"] >= 100 and wrong["rx-packets"] == 0, wrong
    assert instance.terminate(30) == 0


